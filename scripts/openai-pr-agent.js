const fs = require("fs");
const OpenAI = require("openai");

const client = new OpenAI({
  apiKey: process.env.OPENAI_API_KEY,
});

async function run() {
  try {
    const diff = fs.readFileSync("diff.txt", "utf8");
    const context = fs.readFileSync("full_context.txt", "utf8");

    const response = await client.chat.completions.create({
      model: "gpt-4o-mini",
      messages: [
        {
          role: "user",
          content: `
You are a senior software engineer reviewing a PR.

Analyze the following:

--- GIT DIFF ---
${diff}

--- FULL CONTEXT ---
${context}

Return a clean PR review:

## 🐞 Bugs
- ...

## 🔐 Security
- ...

## ⚡ Performance
- ...

## 🧠 Summary
...
          `,
        },
      ],
      temperature: 0.2,
    });

    const review =
      response.choices?.[0]?.message?.content ||
      "⚠️ No review generated by AI";

    // IMPORTANT: return output to GitHub Actions
    process.stdout.write(review);

  } catch (error) {
    console.error("AI Agent Error:", error.message);

    // fallback output (prevents pipeline crash)
    process.stdout.write("⚠️ AI review failed due to error.");
  }
}

run();